const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
 const base=(process.env.INSTALL_BASE_URL||'http://127.0.0.1:8080/')+'web/';
 const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
 const page=await context.newPage();
 const provider='**/api/android/**';
 await page.route(provider,route=>{
  const url=route.request().url();
  const items=url.includes('videoKind/2')?[{nb:'202',en_title:'Series Alpha',ar_title:'مسلسل ألفا',kind:2,year:'2026'}]:[{nb:'101',en_title:'Film Beta',kind:1,year:'2025',rating:'7.5'}];
  const response=url.includes('transcoddedfiles/')?{data:{files:[{resolution:'720p',url:'https://media.example.org/allowed.m3u8'}]}}:
    url.includes('videoSeason/')?{data:{episodes:[{nb:'203',en_title:'Episode 1',episodeNummer:1,season:1}]}}:{data:{items}};
  return route.fulfill({status:200,headers:{'content-type':'application/json','access-control-allow-origin':'*'},body:JSON.stringify(response)});
 });
 await page.goto(base);
 await page.locator('.tile').first().waitFor();
 assert.equal(await page.locator('.tile').count(),2);
 assert.equal(await page.locator('link[rel="manifest"]').count(),1);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.locator('.tile[aria-label="Film Beta"]').click();
 assert.equal(await page.locator('#details').isVisible(),true);
 await page.locator('#toggle-save').click();
 await page.locator('[data-close="details"]').click();
 await page.locator('[data-tab="saved"]').click();
 assert.equal(await page.locator('.tile').count(),1);
 await page.reload();
 await page.locator('[data-tab="saved"]').click();
 assert.equal(await page.locator('.tile').count(),1);
 await page.locator('#language').click();
 assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
 await page.locator('#install-instructions').click();
 assert.equal(await page.locator('#install-dialog').isVisible(),true);
 await page.locator('[data-close="install-dialog"]').click();
 await page.locator('#open-link').click();
 await page.locator('#media-url').fill('javascript:alert(1)');
 await page.locator('#play-link').click();
 assert.equal(await page.locator('#link-error').isVisible(),true);
 await page.locator('[data-close="link-dialog"]').click();
 await page.locator('[data-tab="home"]').click();
 await page.locator('#search').fill('Film Beta');
 await page.locator('.tile').first().waitFor();
 assert.equal(await page.locator('.tile[aria-label="Film Beta"]').count(),1);
 await page.locator('.tile[aria-label="Film Beta"]').click();
 await page.locator('#play').click();
 await page.waitForFunction(()=>document.querySelector('#video').src.endsWith('allowed.m3u8'));
 assert.equal(await page.locator('#player-dialog').isVisible(),true);
 await page.locator('[data-close="player-dialog"]').click();
 await context.close();
 // Failure path: provider cannot be queried from a browser.
 const context2=await browser.newContext({serviceWorkers:'block'});
 const p2=await context2.newPage();await p2.route(provider,r=>r.abort());
 await p2.goto(base);
 await p2.waitForFunction(()=>document.querySelector('#notice').textContent.includes('provider')||document.querySelector('#notice').textContent.includes('CORS'));
 assert.equal(await p2.locator('.tile').count(),0);
 assert.equal(await p2.locator('#notice').isVisible(),true);
 await context2.close();await browser.close();
 console.log('PASS: installable app manifest, EN/AR, responsive layout, catalog, favorites, search, player handoff, and provider failure.');
})().catch(e=>{console.error(e);process.exit(1)});